// Helper to generate full SKILL.md content adhering to the 0. Canonical Skill Package Standard
function generateSkillMdContent(s: RawSkillDefinition): string {
  const packageName = s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return `# Skill: ${s.name} (${s.number})

## Purpose
${s.purpose}

## Scope
- Implement authoritative capabilities across: ${s.mustHave.slice(0, 5).join(', ')}.
- Produce structured outputs conforming to ${s.canonicalArtifacts[0] || 'output.schema.json'}.
- Guarantee deterministic execution across all lifecycle stages.

## Non-Goals
- Performing out-of-scope manual ad-hoc overrides without audit logging.
- Introducing implicit environment-specific dependencies.
- Bypassing schema validation for intermediate artifacts.

## Required Inputs
${s.requiredInputs.map((i) => `- \`${i}\``).join('\n')}

## Optional Inputs
${(s.optionalInputs || ['execution_overrides', 'telemetry_context']).map((i) => `- \`${i}\``).join('\n')}

## Core Responsibilities & Must-Haves
${s.mustHave.map((m) => `- **${m}**: Systematically analyzed and validated.`).join('\n')}

## Decision Methodology
1. **Context Ingestion**: Validate authoritative inputs against input schemas.
2. **Deterministic Assessment**: Evaluate current state, bottlenecks, and dependency health.
3. **Model Generation**: Synthesize structured output models conforming to canonical artifacts.
4. **Acceptance Verification**: Verify zero regressions against formal acceptance criteria.

## Expected Outputs
${s.outputs.map((o) => `- \`${o}\``).join('\n')}

## Canonical Artifacts Owned
${s.canonicalArtifacts.map((a) => `- \`${packageName}/${a}\``).join('\n')}

## Validation Rules
- All required inputs must be structurally non-empty and schema-compliant.
- Output artifacts must pass 100% of JSON schema assertions.
- Cross-skill dependencies (${s.dependencies.join(', ')}) must be resolved prior to final release gating.

## Failure Behavior
- If input validation fails, return structured \`VALIDATION_ERROR\` with precise path pointers.
- If dependencies are missing, enter deterministic \`BLOCKED_DEPENDENCY\` state without side-effects.

## Dependencies
${s.dependencies.map((d) => `- ${d}`).join('\n')}

## Acceptance Criteria
- 100% of unit tests and fixture suites execute green.
- Artifacts written cleanly inside \`${packageName}/\` package boundary.
- Machine-readable manifest validated against canonical schema.

## Handoff Contract
Implementation-ready state verified: Any downstream agent can invoke this skill autonomously without requiring prior conversational context.`;
}

// Helper to build execution contract stages
function generateExecutionContract(s: RawSkillDefinition): UniversalExecutionContract {
  return {
    context: `Ingest and validate environment context, authoritative inputs (${s.requiredInputs.slice(0, 2).join(', ')}), and boundary constraints.`,
    assess: `Analyze current baseline state, identifying capability gaps, structural bottlenecks, and upstream dependencies in ${s.dependencies.join(', ')}.`,
    design: `Architect proposed structured solution, policy models, and governance blueprints adhering to canonical schemas.`,
    plan: `Decompose design into ordered work packages, milestone gates, and deterministic validation rules.`,
    execute: `Generate and write canonical artifacts (${s.canonicalArtifacts.slice(0, 3).join(', ')}) with full schema adherence.`,
    verify: `Execute automated test suites, verify zero regressions, and validate acceptance criteria.`,
    report: `Return structured findings, audit trail logs, telemetry metrics, and handoff contracts.`,
    improve: `Feed verified operational telemetry back into capability models and register optimizations.`,
  };
}

